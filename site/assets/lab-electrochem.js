  /* ======================== часть 2: электролиз ======================== */

  function part2(st, t, B) {
    let s = '';
    const LIQ = 217;                      // уровень раствора в ванне
    const BOT = 285;                      // низ электродов

    /* --- табло состояния --- */
    s += W.rect(8, 8, 258, 66, '#f7fafb', '#d7dbe0', 1, 8);
    s += W.txt(18, 28, st.run
      ? 'I = ' + fx(st.I, 1) + ' А, t = ' + Math.round(st.t / 60)
        + ' мин, Q = ' + fx(st.I * st.t, 0) + ' Кл'
      : 'ток не включён', st.run ? C.ink : C.gray, 11);
    s += W.txt(18, 46, st.run
      ? 'm(теор) = M·I·t/(nF) = ' + fx(mTheor(st), 4) + ' г'
      : 'm(теор) = M·I·t/(nF)', C.gray, 11);
    s += W.txt(18, 64, st.weighed
      ? 'm(практ) = ' + fx(mDep(st), 3) + ' г, η = ' + fx(yieldNow(st), 1) + ' %'
      : 'm₀(катода) = ' + fx(st.m0, 2) + ' г',
      st.weighed ? C.green : C.gray, 11);

    /* --- весы --- */
    const reading = st.onPan
      ? fx(st.weighed ? st.m1 : st.m0, 2) + ' г' : '0,00 г';
    s += W.at(20, B - 62, W.balance(124, 62, reading,
      { label: 'весы, ±0,01 г' }));
    if (st.onPan) {
      const dep = st.weighed ? Math.min(1, mDep(st) / 2) : 0;
      s += W.rect(75, 196, 14, 56, GRAPHITE, C.gray, 1.2, 2);
      if (dep > 0) s += W.rect(73, 214, 18, 38, mixHex('#c98a5e', '#6a3a1f', dep),
        C.gray, 1, 2);
      s += W.txt(82, 188, st.weighed ? 'катод после опыта' : 'катод до опыта',
        C.ink, 10.5, 'middle');
    } else {
      s += W.txt(82, 230, 'весы свободны', C.gray, 10.5, 'middle');
    }

    /* --- источник постоянного тока --- */
    s += W.rect(300, 14, 150, 34, '#eef1f3', C.ink, 1.4, 4);
    s += W.txt(375, 30, 'источник постоянного тока', C.ink, 9.5, 'middle');
    s += W.txt(375, 43, '4 В, регулируемый', C.gray, 9, 'middle');
    s += W.txt(320, 62, '(−)', C.ink, 11, 'end');
    s += W.txt(430, 62, '(+)', C.ink, 11, 'start');

    /* --- ванна с раствором --- */
    s += W.at(280, B - 120, W.beaker(230, 120, 0.72, cuColor(C_BATH)));
    s += W.callout(300, 178, -30, -14, 'раствор CuSO₄, ' + num(C_BATH) + ' моль/л');

    if (st.cellBuilt) {
      /* анод — угольный стержень, на нём пузырьки кислорода */
      s += W.rect(452, 130, 18, BOT - 130, GRAPHITE, C.gray, 1.2, 2);
      s += W.path('M 421 48 V 80 H 461 V 130', C.ink, 1.6);

      /* катод: либо в ванне с наростом меди, либо снят и лежит на весах */
      if (st.onPan) {
        s += W.path('M 320 130 V ' + BOT, '#c7ced3', 1.4, 'none',
          ' stroke-dasharray="4 4"');
      } else {
        s += W.path('M 329 48 V 130', C.ink, 1.6);
        s += W.circle(329, 95, 14, '#fff', C.ink, 1.5);
        s += W.txt(329, 100, 'A', C.ink, 12, 'middle');
        if (st.run) s += W.txt(310, 118, fx(st.I, 1) + ' А', C.ink, 10.5, 'end');
        s += W.rect(320, 130, 18, BOT - 130, GRAPHITE, C.gray, 1.2, 2);
        /* нарост меди: толщина и цвет — по массе осевшего металла */
        if (st.run) {
          const full = Math.min(1, mTheor(st) * ETA / 2);
          const g = st.weighed ? full : full * (0.5 + 0.5 * t);
          const e = 1 + 5 * g;
          s += W.rect(320 - e, LIQ + 2, 18 + 2 * e, BOT - LIQ - 2,
            mixHex('#c98a5e', '#6a3a1f', g), C.gray, 1);
        }
      }

      /* пузырьки кислорода на аноде — пока идёт ток */
      if (st.run && !st.weighed) {
        for (let i = 0; i < 8; i++) {
          const p = (t * 1.15 + i / 8) % 1;
          const y = BOT - 2 - p * (BOT - LIQ - 4);
          const x = 478 + 5 * Math.sin(i * 1.7 + p * 5);
          s += W.circle(x, y, 1.4 + (i % 3) * 0.5, 'rgba(21,94,117,.5)');
        }
      }

      /* --- подписи электродов --- */
      s += W.txt(329, 316, 'катод (−), уголь', C.gray, 10.5, 'middle');
      s += W.txt(461, 316, 'анод (+), уголь', C.gray, 10.5, 'middle');
      s += W.txt(329, 332, 'Cu²⁺ + 2e⁻ → Cu', C.ink, 10.5, 'middle');
      s += W.txt(461, 332, '2H₂O − 4e⁻ → O₂↑ + 4H⁺', C.ink, 10.5, 'middle');
    } else {
      s += W.txt(395, 316, 'электроды ещё не опущены', C.gray, 10.5, 'middle');
    }
    return s;
  }
